CREATE TABLE property_sharing_price (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id      BIGINT        NOT NULL,
    property_facility_id BIGINT        NOT NULL,
    sharing_type         VARCHAR(5)    NOT NULL,
    monthly_rent         DECIMAL(10,2) NOT NULL,
    security_deposit     DECIMAL(10,2) NOT NULL DEFAULT 0,
    ac_charges           DECIMAL(10,2) NOT NULL DEFAULT 0,
    -- Per-day rate for temporary stays: amount = days * per_day_price, editable
    -- by the owner before the single TEMP_STAY invoice is raised.
    per_day_price        DECIMAL(10,2) NOT NULL DEFAULT 0,
    CONSTRAINT uk_prop_sharing UNIQUE (property_facility_id, sharing_type),
    CONSTRAINT fk_psp_facility FOREIGN KEY (property_facility_id) REFERENCES facility (facility_id)
);



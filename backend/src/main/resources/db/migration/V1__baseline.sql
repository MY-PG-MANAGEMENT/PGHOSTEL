-- Mobile uniqueness is NOT enforced here. V10 added a global unique key and V12
-- removed it again: the same mobile may be an active tenant at two different
-- properties, so uniqueness is property-scoped and lives in application code
-- (TenantService.create / PersonRepository.countActiveTenantsByMobileAtProperty).

-- Parent/child edges of the facility tree, dated so history survives a move.
CREATE TABLE facility_group_member (
    facility_group_member_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_facility_id       BIGINT NOT NULL,

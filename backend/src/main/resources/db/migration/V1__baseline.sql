-- One row per incoming HTTP hit, written by com.pgmanager.apilog.ApiLogFilter and
-- purged after logging.api.retention-days by ApiLogCleanupScheduler. Column types
-- must stay in step with the ApiRequestLog entity (ddl-auto is `validate`).
--
-- A BIGINT identity PK rather than a UUID: this is the highest-insert-rate table
-- in the schema, and a monotonic key appends to the rightmost index page instead
-- of scattering writes across the whole index.
CREATE TABLE api_request_log (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- All three are NULL for anonymous/rejected traffic, which is a meaningful
    -- value here (it is how you find unauthenticated probing), not a defect.
    organization_id      BIGINT,
    user_login_id        BIGINT,
    tenant_id            BIGINT,

    -- request_id is the client's X-Request-Id when supplied, else a server UUID.
    request_id           VARCHAR(64),
    session_id           VARCHAR(128),

    request_uri          VARCHAR(512) NOT NULL,
    http_method          VARCHAR(10)  NOT NULL,
    controller_name      VARCHAR(160),
    method_name          VARCHAR(120),

    -- Masked, then truncated to logging.api.max-payload-chars (default 8000).
    -- TEXT is unbounded in PostgreSQL, so the cap is purely the application's.
    request_body         TEXT,
    query_parameters     TEXT,
    request_headers      TEXT,

    response_status_code INT,
    response_body        TEXT,

    request_start_time   TIMESTAMP(6) NOT NULL,
    request_end_time     TIMESTAMP(6),
    execution_time_ms    BIGINT,

    -- Flutter device headers.
    platform             VARCHAR(40),
    app_version          VARCHAR(40),
    build_number         VARCHAR(40),
    device_model         VARCHAR(120),
    manufacturer         VARCHAR(80),
    os_name              VARCHAR(40),
    os_version           VARCHAR(40),

    -- 64 chars covers IPv6; only the first X-Forwarded-For hop is stored.
    client_ip_address    VARCHAR(64),
    network_type         VARCHAR(40),
    user_agent           VARCHAR(512),

    -- SUCCESS | FAILED | EXCEPTION | UNAUTHORIZED | FORBIDDEN | TIMEOUT. Stored as
    -- a string, not an ordinal, so adding a value cannot reinterpret old rows.
    status               VARCHAR(20)  NOT NULL,
    error_code           VARCHAR(120),
    error_message        VARCHAR(1000),

    created_date         TIMESTAMP(6) NOT NULL
);

-- Deliberately no foreign keys to facility/user_login. This is append-only
-- diagnostic data written on every request, including for principals that may
-- later be deleted; an FK would add a lock and a lookup to the hottest insert
-- path and could block a legitimate delete elsewhere.

-- The retention sweep and every time-bounded query. The one index that must exist.
CREATE INDEX idx_arl_created_date ON api_request_log (created_date);

-- Composite, not single-column, for the two dimensions that are always sliced by
-- time as well. A lone organization_id index would be near-useless: low
-- cardinality, and the planner would still filter the date range row by row.
CREATE INDEX idx_arl_org_created  ON api_request_log (organization_id, created_date);
CREATE INDEX idx_arl_user_created ON api_request_log (user_login_id, created_date);

-- Endpoint-level analysis: slowest / most-hit URIs.
CREATE INDEX idx_arl_request_uri ON api_request_log (request_uri);

-- Error triage. Both are low cardinality and only really earn their keep combined
-- with the date, but they stay selective for the rare values (EXCEPTION, 500)
-- anyone actually searches for.
CREATE INDEX idx_arl_status               ON api_request_log (status);
CREATE INDEX idx_arl_response_status_code ON api_request_log (response_status_code);

-- "Is the crash only on build 42?" -- release adoption and per-version failure rates.
CREATE INDEX idx_arl_app_version ON api_request_log (app_version);

-- Support flow: a user reports a failure quoting the X-Request-Id from the response.
CREATE INDEX idx_arl_request_id ON api_request_log (request_id);



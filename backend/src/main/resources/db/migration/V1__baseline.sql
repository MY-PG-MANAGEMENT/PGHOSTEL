    revoked          BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at       TIMESTAMP(6) NOT NULL,
    updated_at       TIMESTAMP(6) NOT NULL,
    CONSTRAINT fk_refresh_user FOREIGN KEY (user_login_id) REFERENCES user_login (user_login_id)
);

CREATE TABLE password_reset_token (
    password_reset_token_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_login_id           BIGINT       NOT NULL,
    token_hash              VARCHAR(255) NOT NULL UNIQUE,
    expires_at              TIMESTAMP(6) NOT NULL,
    used_at                 TIMESTAMP(6),
    created_at              TIMESTAMP(6) NOT NULL,
    CONSTRAINT fk_password_reset_user FOREIGN KEY (user_login_id) REFERENCES user_login (user_login_id)
);

CREATE TABLE user_device (
    user_device_id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_login_id          BIGINT       NOT NULL,
    device_identifier_hash VARCHAR(255) NOT NULL,
    platform               VARCHAR(30)  NOT NULL,
    biometric_enabled      BOOLEAN      NOT NULL DEFAULT FALSE,
    push_token             VARCHAR(500),
    last_seen_at           TIMESTAMP(6) NOT NULL,
    revoked_at             TIMESTAMP(6),
    CONSTRAINT uk_user_device UNIQUE (user_login_id, device_identifier_hash),
    CONSTRAINT fk_user_device_user FOREIGN KEY (user_login_id) REFERENCES user_login (user_login_id)
);

CREATE TABLE user_preference (
    user_login_id    BIGINT       NOT NULL,
    preference_key   VARCHAR(80)  NOT NULL,
    preference_value VARCHAR(1000),
    updated_at       TIMESTAMP(6) NOT NULL,
    PRIMARY KEY (user_login_id, preference_key),
    CONSTRAINT fk_preference_user FOREIGN KEY (user_login_id) REFERENCES user_login (user_login_id)
);


-- =============================================================================
-- SECTION 3 -- Roles and permissions
--
-- role_type is read by the application (RoleType constants must resolve);
-- permission / role_permission are reference data that nothing enforces at
-- runtime -- authorization is @PreAuthorize plus PropertyAccessGuard.
-- =============================================================================

CREATE TABLE role_type (
    role_type_id        VARCHAR(40)  PRIMARY KEY,
    description         VARCHAR(160) NOT NULL,
    parent_role_type_id VARCHAR(40),
    CONSTRAINT fk_role_type_parent FOREIGN KEY (parent_role_type_id) REFERENCES role_type (role_type_id)
);

CREATE TABLE permission (
    permission_id VARCHAR(80)  PRIMARY KEY,
    module_code   VARCHAR(40)  NOT NULL,
    description   VARCHAR(200) NOT NULL
);

CREATE TABLE role_permission (
    role_type_id  VARCHAR(40) NOT NULL,
    permission_id VARCHAR(80) NOT NULL,
    -- LOCALTIMESTAMP, not CURRENT_TIMESTAMP: the latter is timestamptz in
    -- PostgreSQL and would be implicitly cast into this timestamp column.
    from_date     TIMESTAMP(6) NOT NULL DEFAULT LOCALTIMESTAMP(6),
    thru_date     TIMESTAMP(6),
    PRIMARY KEY (role_type_id, permission_id, from_date),
    CONSTRAINT fk_role_permission_role       FOREIGN KEY (role_type_id)  REFERENCES role_type (role_type_id),
    CONSTRAINT fk_role_permission_permission FOREIGN KEY (permission_id) REFERENCES permission (permission_id)
);


-- =============================================================================
-- SECTION 4 -- Occupancy
-- =============================================================================

-- Links a party to a facility with a role over a date range. Active rows have a
-- NULL thru_date. Roles: TENANT (org- and property-level membership), OCCUPANT
-- (a bed), TEMP_OCCUPANT (a temporary stay), PROPERTY_MANAGER (a scoped login's
-- property assignment).
--
-- A temp stay overloads the generic columns rather than getting its own table:
-- from_date = check-in, expected_checkout_date = planned check-out, thru_date =
-- actual check-out, monthly_rent = the editable TOTAL charge for the stay.
CREATE TABLE facility_party (
    facility_party_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id        BIGINT      NOT NULL,
    facility_id            BIGINT      NOT NULL,
    party_id               BIGINT      NOT NULL,
    role_type_id           VARCHAR(30) NOT NULL,
    from_date              DATE        NOT NULL,
    thru_date              DATE,
    expected_checkout_date DATE,
    -- The ALL-IN monthly amount (base rent + AC), so billing totals are the same
    -- everywhere. ac_charges only annotates how much of that total is the AC
    -- premium, which lets an invoice itemize MONTHLY_RENT + AC_CHARGES instead of
    -- one lump sum. Changing either must not change monthly_rent's meaning.
    monthly_rent           DECIMAL(10,2),
    ac_charges             DECIMAL(10,2),
    security_deposit       DECIMAL(10,2),
    created_at             TIMESTAMP(6) NOT NULL,
    updated_at             TIMESTAMP(6) NOT NULL,
    CONSTRAINT fk_fp_org      FOREIGN KEY (organization_id) REFERENCES facility (facility_id),
    CONSTRAINT fk_fp_facility FOREIGN KEY (facility_id)     REFERENCES facility (facility_id),
    CONSTRAINT fk_fp_party    FOREIGN KEY (party_id)        REFERENCES party (party_id)
);

CREATE INDEX idx_facility_party_org      ON facility_party (organization_id);
CREATE INDEX idx_facility_party_facility ON facility_party (facility_id);
CREATE INDEX idx_facility_party_party    ON facility_party (party_id);

-- The two composite indexes that matter (added as V23 against MySQL). Every
-- tenant-list query filters on a combination of (organization_id,
-- facility_id|party_id, role_type_id, thru_date); with only the single-column
-- indexes above the planner could use one column and filtered the rest in memory.
CREATE INDEX idx_fp_org_facility_role_thru ON facility_party (organization_id, facility_id, role_type_id, thru_date);
CREATE INDEX idx_fp_org_party_role_thru    ON facility_party (organization_id, party_id,    role_type_id, thru_date);

-- A sharing-type change is never applied mid-cycle. It is recorded here and
-- applied on effective_date (the tenant's next billing anniversary) by
-- BedTransferScheduler, so the current month's invoice is untouched and the new
-- rent starts with the next cycle. Same-sharing transfers apply inline and never
-- create a row here.
CREATE TABLE scheduled_bed_transfer (
    scheduled_bed_transfer_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id           BIGINT      NOT NULL,
    party_id                  BIGINT      NOT NULL,
    from_bed_facility_id      BIGINT,
    to_bed_facility_id        BIGINT      NOT NULL,
    effective_date            DATE        NOT NULL,
    new_monthly_rent          DECIMAL(10,2),
    new_security_deposit      DECIMAL(10,2),
    status                    VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    note                      VARCHAR(255),
    created_at                TIMESTAMP(6) NOT NULL,
    updated_at                TIMESTAMP(6) NOT NULL
);

CREATE INDEX idx_sbt_due    ON scheduled_bed_transfer (status, effective_date);
CREATE INDEX idx_sbt_party  ON scheduled_bed_transfer (organization_id, party_id, status);
CREATE INDEX idx_sbt_to_bed ON scheduled_bed_transfer (to_bed_facility_id, status);


-- =============================================================================
-- PG Manager -- consolidated PostgreSQL baseline.
--
-- This single file replaces the 31 MySQL migrations V1..V31 that preceded the
-- move to PostgreSQL. It is the NET schema: what those migrations left behind
-- after V24 dropped 15 dead tables + 4 views and V29 dropped subscription_plan.
-- The originals are kept, unmodified and off the classpath, in
-- backend/db/legacy-mysql/ as a historical record.
--
-- Why consolidated rather than 31 ported files: the MySQL flyway_schema_history
-- cannot carry across engines, so nothing is gained by replaying DDL that later
-- migrations undo. Every design decision recorded in the old files' comments has
-- been carried forward into the comments here.
--
-- MySQL -> PostgreSQL type mapping applied throughout:
--     BIGINT AUTO_INCREMENT  ->  BIGINT GENERATED BY DEFAULT AS IDENTITY
--     DATETIME(6) / DATETIME ->  TIMESTAMP(6)          (no time zone, as before)
--     TINYINT(1)             ->  BOOLEAN
--     LONGTEXT               ->  TEXT
--     JSON                   ->  JSONB
--     CHAR(n)                ->  VARCHAR(n)            (see note below)
--     inline INDEX/KEY       ->  a separate CREATE INDEX
--     UNIQUE KEY name (...)  ->  CONSTRAINT name UNIQUE (...)
--
-- CHAR(n) -> VARCHAR(n) is the one deliberate deviation. PostgreSQL's CHAR is
-- blank-padded, so a bpchar column compared against a bound VARCHAR parameter
-- brings padding semantics into queries that never had them under MySQL. The
-- three affected columns (billing_account.currency_code, expense_budget.
-- budget_month, staff_salary_payment.pay_month) always hold exactly-n-character
-- values, so VARCHAR is identical in practice and has no padding trap.
--
-- ddl-auto is `validate`, so the 19 tables that have a JPA @Entity must match
-- their mapping exactly. The remaining tables are JdbcTemplate-only and are not
-- tracked by Hibernate.
-- =============================================================================


-- =============================================================================
-- SECTION 1 -- Party / facility backbone
-- =============================================================================

CREATE TABLE party (
    party_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    party_type_id VARCHAR(30) NOT NULL,
    status        VARCHAR(30) NOT NULL DEFAULT 'ACTIVE',
    created_at    TIMESTAMP(6) NOT NULL,
    updated_at    TIMESTAMP(6) NOT NULL
);

-- The full hierarchy ORGANIZATION -> PROPERTY -> FLOOR -> ROOM -> BED lives in
-- this one polymorphic table; facility_type_id distinguishes the level and an
-- organization is itself a facility row (its facility_id doubles as the
-- organization_id used across every other table).
CREATE TABLE facility (
    facility_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    facility_code    VARCHAR(30),
    organization_id  BIGINT,
    facility_type_id VARCHAR(30)  NOT NULL,
    facility_name    VARCHAR(150) NOT NULL,
    -- For ORGANIZATION rows this is the sender / Reply-To address for tenant
    -- email. Nullable in the schema; mandatory only at org-creation time, which
    -- the API layer enforces.
    email            VARCHAR(160),
    status           VARCHAR(30)  NOT NULL DEFAULT 'ACTIVE',
    sharing_type     VARCHAR(50),
    capacity         INT,
    description      VARCHAR(1000),
    room_number      VARCHAR(30),
    floor_number     INT,
    monthly_rent     DECIMAL(12,2),
    security_deposit DECIMAL(12,2),
    size_sq_ft       DECIMAL(10,2),
    available_from   DATE,
    version          BIGINT       NOT NULL DEFAULT 0,
    amenities_json   JSONB,
    photos_count     INT DEFAULT 0,
    is_ac            BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at       TIMESTAMP(6) NOT NULL,
    updated_at       TIMESTAMP(6) NOT NULL,
    CONSTRAINT uq_facility_code UNIQUE (facility_code),
    CONSTRAINT fk_facility_org FOREIGN KEY (organization_id) REFERENCES facility (facility_id)
);

CREATE INDEX idx_facility_org_type ON facility (organization_id, facility_type_id);

-- facility_code is matched case-insensitively (BulkUploadController.findFacilityByCode /
-- findChildByCode), because under MySQL's ai_ci collation it always was: re-uploading a CSV
-- with "flr_a" resolved to the existing "FLR_A" instead of creating a second floor. This
-- index enforces the same uniqueness the old UNIQUE constraint gave under that collation --
-- uq_facility_code above only stops byte-identical duplicates -- and keeps those lookups
-- index scans.
CREATE UNIQUE INDEX uk_facility_code_lower ON facility (LOWER(facility_code));


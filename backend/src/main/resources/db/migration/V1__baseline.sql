-- The owner-facing "Delete tenant", which never loses data. Nothing is removed
-- from party / person / facility_party / invoice / payment -- a row lands here and
-- the tenant drops out of the lists. Exactly ONE live row per party, and restore
-- DELETES it rather than flagging it, so "is this tenant hidden?" stays a plain
-- existence check; the history lives in audit_log (TENANT_ARCHIVED /
-- TENANT_RESTORED). property_facility_id has no FK on purpose: a property can be
-- removed while its archived tenants remain.
CREATE TABLE tenant_archive (
    tenant_archive_id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id           BIGINT       NOT NULL,
    property_facility_id      BIGINT,
    party_id                  BIGINT       NOT NULL,
    full_name                 VARCHAR(150),
    mobile_number             VARCHAR(20),
    archived_at               TIMESTAMP(6) NOT NULL,
    archived_by_user_login_id BIGINT,
    created_at                TIMESTAMP(6) NOT NULL,
    updated_at                TIMESTAMP(6) NOT NULL,
    CONSTRAINT uk_tenant_archive_party UNIQUE (party_id),
    CONSTRAINT fk_tenant_archive_org   FOREIGN KEY (organization_id) REFERENCES facility (facility_id),
    CONSTRAINT fk_tenant_archive_party FOREIGN KEY (party_id)        REFERENCES party (party_id)
);

CREATE INDEX idx_tenant_archive_org_property ON tenant_archive (organization_id, property_facility_id);



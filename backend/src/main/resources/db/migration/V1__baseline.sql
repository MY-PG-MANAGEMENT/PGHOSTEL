CREATE TABLE user_login (
    user_login_id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    party_id             BIGINT       NOT NULL,
    username             VARCHAR(120) NOT NULL UNIQUE,
    password_hash        VARCHAR(255) NOT NULL,
    role_type_id         VARCHAR(30)  NOT NULL,
    organization_id      BIGINT,
    status               VARCHAR(30)  NOT NULL DEFAULT 'ACTIVE',
    -- Why a login is INACTIVE (CHECKED_OUT, ARCHIVED, ...).
    disabled_reason      VARCHAR(40),
    -- Forces a first-login password change; set with the temp password abc@123.
    must_change_password BOOLEAN      NOT NULL DEFAULT FALSE,
    last_login_at        TIMESTAMP(6),
    created_at           TIMESTAMP(6) NOT NULL,
    updated_at           TIMESTAMP(6) NOT NULL,
    CONSTRAINT fk_user_party FOREIGN KEY (party_id)        REFERENCES party (party_id),
    CONSTRAINT fk_user_org   FOREIGN KEY (organization_id) REFERENCES facility (facility_id)
);

-- Usernames are matched case-insensitively (MySQL's utf8mb4_0900_ai_ci did this
-- implicitly; PostgreSQL does not). AuthService lowercases both sides of the
-- lookup, and this index is what keeps that lookup an index scan.
CREATE UNIQUE INDEX uk_user_login_username_lower ON user_login (LOWER(username));

CREATE TABLE refresh_token (
    refresh_token_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_login_id    BIGINT       NOT NULL,
